/**
 * Renders one icon from the set above.
 *
 * @param {object} props
 * @param {keyof PATHS} props.name  which icon to draw
 * @param {number} props.size      width and height in pixels
 * @param {string} [props.className] extra class names for styling
 */
export default function Icon({ name, size = 18, className = '' }) {
  const path = PATHS[name]
  if (!path) return null

  return (
    <svg
      className={`icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {path}
    </svg>
  )
}
